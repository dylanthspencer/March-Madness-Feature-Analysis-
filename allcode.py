#3. Empirical matchup rates (built on train only)

rates = (
    train.groupby(["lo_seed", "hi_seed"])
    .agg(games=("lo_won", "count"), lo_wins=("lo_won", "sum"))
    .reset_index()
)
rates["win_rate"] = rates["lo_wins"] / rates["games"]

def predict_matchup(row):
    team1_seed = row["T1_seed"]
    team2_seed = row["T2_seed"]
    lower_seed = min(team1_seed, team2_seed)
    higher_seed = max(team1_seed, team2_seed)
 #Look up past games with this same seed matchup
    matchup = rates[
        (rates["lo_seed"] == lower_seed) &
        (rates["hi_seed"] == higher_seed)
    ]
    # If there is not enough data, predict that the better seed wins
    if matchup.empty or matchup["games"].values[0] < 20:
        team1_probability = 1 if team1_seed < team2_seed else 0
    else: #If there is enough data, use the historical win rate
        lower_seed_win_rate = matchup["win_rate"].values[0]

        if team1_seed < team2_seed:
            team1_probability = lower_seed_win_rate
        else:
            team1_probability = 1 - lower_seed_win_rate

    return int(team1_probability > 0.5)

