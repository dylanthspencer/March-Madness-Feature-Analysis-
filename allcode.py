def extract_barttorvik(year, cutoff_date):
    # end=<Selection Sunday> — excludes tournament games
    url = (
        f'https://barttorvik.com/teamslicejson.php'
        f'?year={year}&json=1&type=All'
        f'&begin={year-1}1101&end={cutoff_date}'
    )
    r = requests.get(url, headers=headers)
    data = r.json()

    records = []
    for row in data:
        records.append({
            'team':      row[0],
            'adjoe':     row[1],
            'adjde':     row[2],
            'barthag':   row[3],
            'record':    row[4],
            'wins':      row[5],
            'losses':    row[6],
            'efg':       row[7],
            'efgd':      row[8],
            'ftr':       row[9],
            'ftrd':      row[10],
            'tor':       row[11],
            'tord':      row[12],
            'orb':       row[13],
            'drb':       row[14],
            '2p':        row[16],
            '2pd':       row[17],
            '3p':        row[18],
            '3pd':       row[19],
            '3pr':       row[24],
            '3prd':      row[25],
            'adj_tempo': row[26],
            'wab':       row[34],
            'year':      year,
        })
    return pd.DataFrame(records)


